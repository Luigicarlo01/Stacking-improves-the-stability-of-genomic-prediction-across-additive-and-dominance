def clean_df(df):
    """Remove colunas de índice criadas automaticamente pelo pandas."""
    return df.loc[:, ~df.columns.astype(str).str.startswith("Unnamed:")].copy()


_CSV_PREPARED_CACHE = {}


def detect_csv_separator(path):
    """Detecta o separador mais provável sem carregar o arquivo inteiro."""
    path = Path(path)
    sample_lines = []
    with path.open("r", encoding="utf-8-sig", errors="replace", newline="") as handle:
        for _ in range(8):
            line = handle.readline()
            if not line:
                break
            if line.strip():
                sample_lines.append(line)

    sample = "".join(sample_lines)
    if not sample:
        raise ValueError(f"Arquivo vazio: {path}")

    try:
        return csv.Sniffer().sniff(sample, delimiters=",;\t|").delimiter
    except csv.Error:
        candidates = [",", ";", "\t", "|"]
        scores = {}
        for separator in candidates:
            counts = [line.count(separator) for line in sample_lines]
            positive = [count for count in counts if count > 0]
            scores[separator] = (len(positive), np.median(positive) if positive else -1)
        return max(scores, key=scores.get)


def prepare_csv_for_pandas(path):
    """
    Valida a largura das linhas do CSV.

    Corrige automaticamente somente separadores vazios excedentes no fim da
    linha, como `...,1,2,3,,`. Valores extras reais nunca são descartados.
    """
    path = Path(path)
    cache_key = (str(path.resolve()), path.stat().st_size, path.stat().st_mtime_ns)
    if cache_key in _CSV_PREPARED_CACHE:
        return _CSV_PREPARED_CACHE[cache_key]

    separator = detect_csv_separator(path)
    sample_widths = []

    with path.open("r", encoding="utf-8-sig", errors="replace", newline="") as handle:
        reader = csv.reader(handle, delimiter=separator)
        for row in reader:
            if not row or all(not str(value).strip() for value in row):
                continue
            sample_widths.append(len(row))
            if len(sample_widths) >= 200:
                break

    if not sample_widths:
        raise ValueError(f"Arquivo vazio ou sem campos válidos: {path}")

    expected_fields = Counter(sample_widths).most_common(1)[0][0]
    safe_lines = []
    unsafe_lines = []

    with path.open("r", encoding="utf-8-sig", errors="replace", newline="") as handle:
        reader = csv.reader(handle, delimiter=separator)
        for line_number, row in enumerate(reader, start=1):
            if not row or all(not str(value).strip() for value in row):
                continue
            field_count = len(row)
            if field_count == expected_fields:
                continue

            if field_count > expected_fields and all(
                not str(value).strip() for value in row[expected_fields:]
            ):
                safe_lines.append((line_number, field_count))
            else:
                unsafe_lines.append((line_number, field_count, row))
                if len(unsafe_lines) >= 5:
                    break

    if unsafe_lines:
        details = []
        for line_number, field_count, row in unsafe_lines:
            tail = row[max(0, expected_fields - 3): expected_fields + 5]
            details.append(
                f"linha {line_number}: {field_count} campos; "
                f"esperados {expected_fields}; trecho={tail!r}"
            )
        raise ValueError(
            f"CSV malformado em {path.name}. "
            + " | ".join(details)
            + ". Há valores extras ou campos ausentes; o pipeline não os "
              "descartou para não alterar indivíduos ou marcadores."
        )

    if not safe_lines:
        result = (path, separator)
        _CSV_PREPARED_CACHE[cache_key] = result
        print(
            f"CSV validado: {path.name} | separador={separator!r} | "
            f"{expected_fields} campos por linha"
        )
        return result

    corrected_dir = OUT / "csv_corrigidos"
    corrected_dir.mkdir(parents=True, exist_ok=True)
    corrected_path = corrected_dir / f"{path.stem}_corrigido{path.suffix}"
    corrected_line_numbers = {line_number for line_number, _ in safe_lines}

    with path.open("r", encoding="utf-8-sig", errors="replace", newline="") as source, \
         corrected_path.open("w", encoding="utf-8", newline="") as target:
        reader = csv.reader(source, delimiter=separator)
        writer = csv.writer(target, delimiter=separator, lineterminator="\n")
        for line_number, row in enumerate(reader, start=1):
            if line_number in corrected_line_numbers:
                row = row[:expected_fields]
            writer.writerow(row)

    print(
        f"CSV corrigido com segurança: {path.name} | "
        f"{len(safe_lines)} linha(s) com separadores vazios excedentes | "
        f"arquivo usado: {corrected_path}"
    )

    result = (corrected_path, separator)
    _CSV_PREPARED_CACHE[cache_key] = result
    return result


def read_csv_robust(path, header="infer"):
    """Leitura estrita do CSV após validação estrutural."""
    prepared_path, separator = prepare_csv_for_pandas(path)
    return pd.read_csv(
        prepared_path,
        sep=separator,
        header=header,
        engine="c",
        low_memory=False,
    )


def read_y(path):
    """Lê Y em uma coluna, uma linha ou no formato ID + valor."""
    if not path.exists():
        raise FileNotFoundError(f"Arquivo não encontrado: {path}")

    candidates = []
    for df, has_header, label in [
        (read_csv_robust(path), True, "com cabeçalho"),
        (read_csv_robust(path, header=None), False, "sem cabeçalho"),
    ]:
        df = clean_df(df)
        if df.empty:
            continue

        if df.shape[1] == 1:
            values = pd.to_numeric(df.iloc[:, 0], errors="coerce")
            valid_fraction = values.notna().mean()
            if valid_fraction > 0.95:
                y = values.dropna().to_numpy(float)
                ids = np.array([f"ID_{i + 1}" for i in range(len(y))])
                candidates.append((valid_fraction, y, ids, False, f"uma coluna, {label}"))

        if df.shape[0] == 1:
            values = pd.to_numeric(df.iloc[0], errors="coerce")
            valid_fraction = values.notna().mean()
            if valid_fraction > 0.95:
                keep = values.notna().to_numpy()
                y = values[keep].to_numpy(float)
                ids = df.columns.astype(str).to_numpy()[keep]
                candidates.append((valid_fraction + 0.01, y, ids, has_header, f"uma linha, {label}"))

        numeric = df.apply(pd.to_numeric, errors="coerce")
        valid_columns = [c for c in numeric.columns if numeric[c].notna().mean() > 0.95]
        if len(valid_columns) == 1:
            value_column = valid_columns[0]
            valid_rows = numeric[value_column].notna()
            y = numeric.loc[valid_rows, value_column].to_numpy(float)
            other_columns = [c for c in df.columns if c != value_column]
            if other_columns:
                ids = df.loc[valid_rows, other_columns[0]].astype(str).to_numpy()
                explicit_ids = True
            else:
                ids = np.array([f"ID_{i + 1}" for i in range(len(y))])
                explicit_ids = False
            score = numeric[value_column].notna().mean() + 0.02 * explicit_ids
            candidates.append((score, y, ids, explicit_ids, f"ID + valor, {label}"))

    if not candidates:
        raise ValueError(f"Não foi possível identificar a variável resposta em {path.name}.")

    _, y, ids, explicit_ids, description = max(candidates, key=lambda item: item[0])
    if len(y) == 0 or not np.isfinite(y).all():
        raise ValueError(f"{path.name} contém valores inválidos.")

    print(f"\n{path.name}: {description}; {len(y)} indivíduos")
    return y, np.asarray(ids, dtype=str), explicit_ids


def genotype_score(df):
    arr = df.to_numpy(dtype=float)
    finite = np.isfinite(arr)
    if not finite.any():
        return -np.inf
    values = arr[finite]
    return (
        2.0 * finite.mean()
        + np.mean((values >= -0.05) & (values <= 2.05))
        + 0.5 * np.mean(np.isclose(values, np.rint(values), atol=0.05))
    )


def orient_genotypes(path, n_individuals, dataset_name):
    """Converte X automaticamente para linhas=indivíduos e colunas=marcadores."""
    if not path.exists():
        raise FileNotFoundError(f"Arquivo não encontrado: {path}")

    candidates = []
    for raw, has_header, label in [
        (read_csv_robust(path), True, "com cabeçalho"),
        (read_csv_robust(path, header=None), False, "sem cabeçalho"),
    ]:
        df = clean_df(raw)
        if df.empty:
            continue

        # Indivíduos já estão nas linhas.
        if df.shape[0] == n_individuals:
            work = df.copy()
            ids = np.array([f"{dataset_name}_{i + 1}" for i in range(n_individuals)])
            explicit_ids = False

            if work.shape[1] > 1:
                first_numeric = pd.to_numeric(work.iloc[:, 0], errors="coerce")
                if first_numeric.notna().mean() < 0.80:
                    ids = work.iloc[:, 0].astype(str).to_numpy()
                    work = work.iloc[:, 1:]
                    explicit_ids = True

            X = work.apply(pd.to_numeric, errors="coerce")
            candidates.append({
                "score": genotype_score(X),
                "X": X,
                "ids": ids,
                "explicit_ids": explicit_ids,
                "description": f"indivíduos nas linhas, {label}",
            })

        # Indivíduos estão nas colunas.
        if df.shape[1] == n_individuals:
            numeric = df.apply(pd.to_numeric, errors="coerce")
            X = numeric.T
            X.columns = [f"M{i + 1}" for i in range(X.shape[1])]
            candidates.append({
                "score": genotype_score(numeric) + 0.001 * X.shape[1],
                "X": X,
                "ids": df.columns.astype(str).to_numpy(),
                "explicit_ids": has_header,
                "description": f"matriz transposta, {label}",
            })

        # Primeira coluna contém IDs dos marcadores.
        if df.shape[1] - 1 == n_individuals:
            marker_ids = df.iloc[:, 0].astype(str).to_numpy()
            numeric = df.iloc[:, 1:].apply(pd.to_numeric, errors="coerce")
            X = numeric.T
            X.columns = marker_ids
            candidates.append({
                "score": genotype_score(numeric) + 0.05,
                "X": X,
                "ids": df.columns[1:].astype(str).to_numpy(),
                "explicit_ids": has_header,
                "description": f"transposta com IDs de marcadores, {label}",
            })

    viable = []
    for candidate in candidates:
        X = candidate["X"]
        numeric_fraction = np.isfinite(X.to_numpy(float)).mean()
        if X.shape[0] == n_individuals and numeric_fraction > 0.90:
            viable.append(candidate)

    if not viable:
        raise ValueError(
            f"Não foi possível orientar {dataset_name} para {n_individuals} indivíduos."
        )

    selected = max(viable, key=lambda item: item["score"])
    X = selected["X"].reset_index(drop=True)

