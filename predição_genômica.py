def fit_neural_network(model_name, builder, X_all, target_all, X_external_test):
    """
    Usa 20% do treino como validação interna para escolher o número de épocas.
    O teste externo não participa do early stopping.
    """
    indices = np.arange(len(target_all))
    fit_idx, val_idx = train_test_split(
        indices,
        test_size=0.20,
        random_state=SEED,
    )

    keras.backend.clear_session()
    tf.keras.utils.set_random_seed(SEED)

    selector = builder()
    history = selector.fit(
        X_all[fit_idx],
        target_all[fit_idx],
        validation_data=(X_all[val_idx], target_all[val_idx]),
        epochs=EPOCHS_MAX,
        batch_size=BATCH_SIZE,
        verbose=0,
        callbacks=[
            keras.callbacks.EarlyStopping(
                monitor="val_loss",
                patience=PATIENCE,
                restore_best_weights=True,
            ),
            keras.callbacks.ReduceLROnPlateau(
                monitor="val_loss",
                factor=0.5,
                patience=5,
                min_lr=1e-6,
            ),
        ],
    )

    best_epoch = int(np.argmin(history.history["val_loss"]) + 1)
    del selector
    keras.backend.clear_session()
    gc.collect()

    tf.keras.utils.set_random_seed(SEED)
    final_model = builder()
    final_model.fit(
        X_all,
        target_all,
        epochs=best_epoch,
        batch_size=BATCH_SIZE,
        verbose=0,
    )
    prediction = final_model.predict(X_external_test, verbose=0).ravel()

    del final_model
    keras.backend.clear_session()
    gc.collect()

    print(f"{model_name}: melhor época interna = {best_epoch}")
    return prediction

