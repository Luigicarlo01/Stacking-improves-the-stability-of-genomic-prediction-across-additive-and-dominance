def exact_top_indices(values, fraction=TOP_FRAC):
    k = max(1, int(np.ceil(fraction * len(values))))
    return np.argsort(values, kind="mergesort")[-k:]


def hit_rate(y_true, y_pred):
    true_top = exact_top_indices(y_true)
    pred_top = exact_top_indices(y_pred)
    return float(len(np.intersect1d(true_top, pred_top)) / len(pred_top))


def ndcg_score_rank(y_true, y_pred):
    k = max(1, int(np.ceil(TOP_FRAC * len(y_true))))
    relevance = rankdata(y_true, method="average") - 1.0
    predicted_order = np.argsort(y_pred, kind="mergesort")[::-1][:k]
    ideal_order = np.argsort(relevance, kind="mergesort")[::-1][:k]
    discounts = np.log2(np.arange(2, k + 2))
    dcg = np.sum(relevance[predicted_order] / discounts)
    idcg = np.sum(relevance[ideal_order] / discounts)
    return float(dcg / idcg) if idcg > 0 else np.nan


def calibration_slope(y_true, y_pred):
    if np.std(y_pred) < 1e-12:
        return np.nan
    model = LinearRegression().fit(y_pred.reshape(-1, 1), y_true)
    return float(model.coef_[0])


def predictive_pearson(y_true, y_pred):
    """Correlação de Pearson entre valores reais e preditos.

    Em seleção genômica, esta métrica costuma ser chamada de acurácia
    preditiva genômica. Ela é diferente da correlação entre resíduos.
    """
    y_true = np.asarray(y_true, dtype=float).ravel()
    y_pred = np.asarray(y_pred, dtype=float).ravel()

    if (
        len(y_true) < 2
        or len(y_true) != len(y_pred)
        or not np.isfinite(y_true).all()
        or not np.isfinite(y_pred).all()
        or np.std(y_true) < 1e-12
        or np.std(y_pred) < 1e-12
    ):
        return np.nan

    return float(pearsonr(y_true, y_pred)[0])


def calculate_metrics(y_true_orig, y_pred_orig, y_true_norm, y_pred_norm):
    """
    Calcula as métricas individuais de cada modelo.

    A acurácia preditiva é Pearson(real, predito). A correlação par a par
    entre os resíduos continua sendo calculada separadamente apenas no final.
    """
    residuals = np.asarray(y_true_orig) - np.asarray(y_pred_orig)
    return {
        "Acurácia preditiva (Pearson)": predictive_pearson(
            y_true_orig,
            y_pred_orig,
        ),
        "R²": float(r2_score(y_true_orig, y_pred_orig)),
        "SRMSE": float(np.sqrt(mean_squared_error(y_true_norm, y_pred_norm))),
        "RMSE original": float(np.sqrt(mean_squared_error(y_true_orig, y_pred_orig))),
        "MAE original": float(mean_absolute_error(y_true_orig, y_pred_orig)),
        "Viés médio": float(np.mean(np.asarray(y_pred_orig) - np.asarray(y_true_orig))),
        "Viés (b)": calibration_slope(y_true_orig, y_pred_orig),
        "Variância dos resíduos": float(np.var(residuals, ddof=1)),
        "Desvio dos resíduos": float(np.std(residuals, ddof=1)),
        "Hit Rate": hit_rate(y_true_orig, y_pred_orig),
        "NDCG": ndcg_score_rank(y_true_orig, y_pred_orig),
    }


