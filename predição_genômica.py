def select_tabpfn_features(X_train_raw, y_train, max_features):
    """
    Seleciona marcadores pela correlação absoluta com Y usando somente o treino.

    A implementação evita criar uma cópia centralizada gigante da matriz.
    Retorna os índices selecionados ordenados por importância decrescente.
    """
    X_array = np.asarray(X_train_raw, dtype=np.float64)
    y_array = np.asarray(y_train, dtype=np.float64).ravel()

    n_samples, n_features = X_array.shape
    if n_features <= max_features:
        return np.arange(n_features, dtype=int)

    sum_x = np.sum(X_array, axis=0)
    sum_x2 = np.einsum("ij,ij->j", X_array, X_array)
    sum_y = float(np.sum(y_array))
    sum_y2 = float(np.dot(y_array, y_array))

    covariance_numerator = X_array.T @ y_array - (sum_x * sum_y / n_samples)
    variance_x_numerator = sum_x2 - (sum_x ** 2 / n_samples)
    variance_y_numerator = sum_y2 - (sum_y ** 2 / n_samples)

    denominator = np.sqrt(
        np.maximum(variance_x_numerator, 0.0)
        * max(variance_y_numerator, 0.0)
    )

    absolute_correlation = np.divide(
        np.abs(covariance_numerator),
        denominator,
        out=np.zeros_like(covariance_numerator, dtype=float),
        where=denominator > 1e-12,
    )

    k = min(int(max_features), n_features)
    selected = np.argpartition(absolute_correlation, -k)[-k:]
    selected = selected[np.argsort(absolute_correlation[selected])[::-1]]
    return selected.astype(int)



