# ================================================================
# 8. IDENTIFICAR AUTOMATICAMENTE AS COLUNAS DE SNPs
#
# Uma coluna é considerada SNP quando:
#   - pelo menos 95% dos valores não ausentes podem ser convertidos
#     para números;
#   - todos os valores observados estão entre 0 e 2.
#
# Isso evita aplicar os filtros em colunas como ID.
# ================================================================

def coluna_parece_snp(serie):

    valores_nao_ausentes = serie.notna()

    quantidade_observada = valores_nao_ausentes.sum()

    if quantidade_observada == 0:

        return False

    valores_numericos = pd.to_numeric(
        serie,
        errors="coerce"
    )

    taxa_conversao = (
        valores_numericos[valores_nao_ausentes]
        .notna()
        .mean()
    )

    if taxa_conversao < 0.95:

        return False

    valores_validos = (
        valores_numericos
        .dropna()
        .to_numpy(dtype=np.float64)
    )

    if len(valores_validos) == 0:

        return False

    dentro_intervalo = np.all(
        (valores_validos >= 0)
        & (valores_validos <= 2)
    )

    return bool(dentro_intervalo)


