def fit_base_with_oof_cache(model_name, builder):
    """
    Executa os folds uma única vez para produzir as previsões OOF usadas
    pelo stacking. Depois ajusta uma versão final em todo o treino para
    a avaliação individual no teste externo.

    Quando o stacking for executado, os modelos-base não serão treinados
    novamente: apenas as previsões armazenadas serão reutilizadas.
    """
    if model_name in stacking_base_cache:
        print(f"{model_name}: reutilizando predições do cache.")
        return stacking_base_cache[model_name]["final_test_prediction"]

    print(f"{model_name}: executando {len(cv_splits)} folds para o stacking.")

    oof_prediction = np.zeros(len(ytr), dtype=float)
    fold_test_predictions = []

    for fold, (train_idx, val_idx) in enumerate(cv_splits, start=1):
        fold_start = time.time()
        model = builder()
        model.fit(Xtr[train_idx], ytr[train_idx])

        val_prediction = np.asarray(
            model.predict(Xtr[val_idx]), dtype=float
        ).ravel()
        test_prediction = np.asarray(model.predict(Xte), dtype=float).ravel()

        oof_prediction[val_idx] = val_prediction
        fold_test_predictions.append(test_prediction)

        fold_residuals = ytr[val_idx] - val_prediction
        fold_metrics = {
            "Modelo": model_name,
            "Fold": fold,
            "N_treino": len(train_idx),
            "N_validação": len(val_idx),
            "Acurácia preditiva (Pearson)": predictive_pearson(
                ytr[val_idx],
                val_prediction,
            ),
            "R²": float(r2_score(ytr[val_idx], val_prediction)),
            "SRMSE": float(np.sqrt(mean_squared_error(ytr[val_idx], val_prediction))),
            "Viés médio": float(np.mean(val_prediction - ytr[val_idx])),
            "Variância dos resíduos": float(np.var(fold_residuals, ddof=1)),
            "Tempo (s)": time.time() - fold_start,
        }
        cv_records.append(fold_metrics)

        print(
            f"  Fold {fold}/{len(cv_splits)}"
            f" | Pearson={fold_metrics['Acurácia preditiva (Pearson)']:.4f}"
            f" | R²={fold_metrics['R²']:.4f}"
            f" | SRMSE={fold_metrics['SRMSE']:.4f}"
            f" | Viés OOF norm.={fold_metrics['Viés médio']:.4f}"
            f" | Var.Res. OOF norm.={fold_metrics['Variância dos resíduos']:.4f}"
            f" | Tempo={fold_metrics['Tempo (s)']:.2f}s"
        )

        del model
        gc.collect()

    stacking_test_prediction = np.mean(
        np.vstack(fold_test_predictions),
        axis=0,
    )

    oof_residuals = ytr - oof_prediction
    oof_pearson = predictive_pearson(ytr, oof_prediction)
    oof_r2 = float(r2_score(ytr, oof_prediction))
    oof_srmse = float(np.sqrt(mean_squared_error(ytr, oof_prediction)))
    oof_bias = float(np.mean(oof_prediction - ytr))
    oof_variance = float(np.var(oof_residuals, ddof=1))

    print(
        f"{model_name}: OOF consolidado"
        f" | Pearson={oof_pearson:.4f}"
        f" | R²={oof_r2:.4f}"
        f" | SRMSE={oof_srmse:.4f}"
        f" | Viés OOF norm.={oof_bias:.4f}"
        f" | Var.Res. OOF norm.={oof_variance:.4f}"
    )

    print(f"{model_name}: ajustando versão final em todo o treino.")
    final_model = builder()
    final_model.fit(Xtr, ytr)
    final_test_prediction = np.asarray(
        final_model.predict(Xte), dtype=float
    ).ravel()

    stacking_base_cache[model_name] = {
        "oof_prediction": oof_prediction,
        "stacking_test_prediction": stacking_test_prediction,
        "final_test_prediction": final_test_prediction,
        "oof_pearson": oof_pearson,
        "oof_r2": oof_r2,
        "oof_srmse": oof_srmse,
        "oof_bias": oof_bias,
        "oof_residual_variance": oof_variance,
    }

    del final_model
    gc.collect()
    return final_test_prediction


def fit_stacking():
    """
    Treina somente o meta-modelo, reutilizando as predições OOF.

    RidgeCV foi desativado apenas como base de alta dimensionalidade.
    O código original permanece comentado para reativação futura.
    """
    base_names = [
        # "RidgeCV",  # DESATIVADO como base pesada
        "Bayesian Ridge",
        "CatBoost",
    ]

    builders = {
        # "RidgeCV": lambda: RidgeCV(
        #     alphas=np.logspace(-3, 3, 100)
        # ),
        "Bayesian Ridge": lambda: BayesianRidge(),
        "CatBoost": catboost_model,
    }

    for model_name in base_names:
        if model_name not in stacking_base_cache:
            print(f"{model_name} ainda não está no cache; executando agora.")
            fit_base_with_oof_cache(model_name, builders[model_name])
        else:
            print(f"{model_name}: previsões OOF reutilizadas.")

    stack_train = np.column_stack([
        stacking_base_cache[name]["oof_prediction"]
        for name in base_names
    ])
    stack_test = np.column_stack([
        stacking_base_cache[name]["stacking_test_prediction"]
        for name in base_names
    ])

    print("Stacking: treinando somente o meta-modelo RidgeCV.")
    meta_model = RidgeCV(alphas=np.logspace(-3, 3, 100))
    meta_model.fit(stack_train, ytr)

    stacking_oof = meta_model.predict(stack_train)
    stacking_test = meta_model.predict(stack_test)

    oof_residuals = ytr - stacking_oof
    oof_pearson = predictive_pearson(ytr, stacking_oof)
    oof_r2 = float(r2_score(ytr, stacking_oof))
    oof_srmse = float(np.sqrt(mean_squared_error(ytr, stacking_oof)))
    oof_bias = float(np.mean(stacking_oof - ytr))
    oof_variance = float(np.var(oof_residuals, ddof=1))

    stacking_meta_info.clear()
    stacking_meta_info.update({
        "alpha": float(meta_model.alpha_),
        "intercepto": float(meta_model.intercept_),
        "Acurácia preditiva (Pearson) OOF": oof_pearson,
        "R² OOF": oof_r2,
        "SRMSE OOF": oof_srmse,
        "Viés OOF": oof_bias,
        "Variância residual OOF": oof_variance,
        "coeficientes": {
            name: float(coef)
            for name, coef in zip(base_names, np.ravel(meta_model.coef_))
        },
    })

    print(
        f"Stacking OOF interno do fold externo"
        f" | Pearson={oof_pearson:.4f}"
        f" | R²={oof_r2:.4f}"
        f" | SRMSE={oof_srmse:.4f}"
        f" | Viés OOF norm.={oof_bias:.4f}"
        f" | Var.Res. OOF norm.={oof_variance:.4f}"
        f" | alpha={meta_model.alpha_:.6g}"
    )
    print("Pesos do meta-modelo:")
    for name, coefficient in stacking_meta_info["coeficientes"].items():
        print(f"  {name}: {coefficient:.6f}")
    print(f"  Intercepto: {meta_model.intercept_:.6f}")

    return stacking_test


