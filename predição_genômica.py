def build_attention_net():
    """AttentionNet original com projeção densa para 16 blocos de 32."""
    input_layer = layers.Input(
        shape=(n_markers,),
    )

    x = layers.Dense(
        512,
        activation="relu",
    )(
        input_layer
    )

    sequence_length = 16
    embedding_dimension = 32

    # 16 * 32 = 512; a condição é mantida para segurança.
    if x.shape[-1] != sequence_length * embedding_dimension:
        x = layers.Dense(
            sequence_length * embedding_dimension,
            activation="relu",
        )(
            x
        )

    projected = layers.Reshape(
        (sequence_length, embedding_dimension)
    )(
        x
    )

    attention = layers.MultiHeadAttention(
        num_heads=4,
        key_dim=8,
    )(
        projected,
        projected,
    )

    pooled = layers.GlobalAveragePooling1D()(
        attention
    )

    x = layers.Concatenate()([
        layers.Flatten()(x),
        pooled,
    ])

    x = layers.Dense(
        128,
        activation="relu",
    )(
        x
    )

    output = layers.Dense(1)(
        x
    )

    model = keras.Model(
        input_layer,
        output,
    )

    return compile_model(
        model,
        learning_rate=1e-3,
    )


