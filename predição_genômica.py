def fit_rkhs_rbf():
    landmarks = landmark_indices()
    X_landmarks = Xtr[landmarks]

    distance_train = pairwise_distances(Xtr, X_landmarks, metric="sqeuclidean")
    distance_test = pairwise_distances(Xte, X_landmarks, metric="sqeuclidean")
    distance_landmarks = pairwise_distances(
        X_landmarks, X_landmarks, metric="sqeuclidean"
    )

    upper_triangle = distance_landmarks[
        np.triu_indices_from(distance_landmarks, k=1)
    ]
    positive_distances = upper_triangle[upper_triangle > 0]
    median_distance = (
        float(np.median(positive_distances))
        if len(positive_distances)
        else 1.0
    )

    best_configuration = None
    for theta in [0.25, 1.0, 4.0]:
        gamma = theta / median_distance
        train_cross_kernel = np.exp(-gamma * distance_train)
        landmark_kernel = np.exp(-gamma * distance_landmarks)
        transform = nystrom_transform(landmark_kernel)
        train_features = train_cross_kernel @ transform

        model = RidgeCV(
            alphas=np.logspace(-3, 3, 20),
            cv=min(3, n_folds),
            scoring="neg_root_mean_squared_error",
        ).fit(train_features, ytr)

        candidate = (
            -float(model.best_score_),
            theta,
            gamma,
            float(model.alpha_),
        )
        if best_configuration is None or candidate[0] < best_configuration[0]:
            best_configuration = candidate

    _, best_theta, best_gamma, best_alpha = best_configuration

    landmark_kernel = np.exp(-best_gamma * distance_landmarks)
    transform = nystrom_transform(landmark_kernel)
    train_features = np.exp(-best_gamma * distance_train) @ transform
    test_features = np.exp(-best_gamma * distance_test) @ transform

    final_model = Ridge(alpha=best_alpha).fit(train_features, ytr)
    print(
        f"RKHS: theta={best_theta}, alpha={best_alpha:.6g}, "
        f"landmarks={len(landmarks)}"
    )
    return final_model.predict(test_features)


def genomic_cross_kernel(X1, X2, allele_frequency, component):
    p = allele_frequency
    q = 1.0 - p

    if component == "A":
        Z1 = X1 - 2.0 * p
        Z2 = X2 - 2.0 * p
        denominator = max(2.0 * np.sum(p * q), 1e-12)
        return (Z1 @ Z2.T) / denominator

    if component == "D":
        genotype_1 = np.rint(X1).clip(0, 2)
        genotype_2 = np.rint(X2).clip(0, 2)

        dominance_1 = np.where(
            genotype_1 < 0.5,
            -2.0 * p**2,
            np.where(genotype_1 < 1.5, 2.0 * p * q, -2.0 * q**2),
        )
        dominance_2 = np.where(
            genotype_2 < 0.5,
            -2.0 * p**2,
            np.where(genotype_2 < 1.5, 2.0 * p * q, -2.0 * q**2),
        )

        denominator = max(np.sum((2.0 * p * q) ** 2), 1e-12)
        return (dominance_1 @ dominance_2.T) / denominator

    raise ValueError("Componente genômico inválido.")


def fit_rkhs_extended():
    landmarks = landmark_indices()
    X_landmarks = Xtr_raw[landmarks]

    p = Xtr_raw.mean(axis=0) / 2.0
    q = 1.0 - p

    A_train = genomic_cross_kernel(Xtr_raw, X_landmarks, p, "A")
    A_test = genomic_cross_kernel(Xte_raw, X_landmarks, p, "A")
    A_landmarks = genomic_cross_kernel(X_landmarks, X_landmarks, p, "A")

    D_train = genomic_cross_kernel(Xtr_raw, X_landmarks, p, "D")
    D_test = genomic_cross_kernel(Xte_raw, X_landmarks, p, "D")
    D_landmarks = genomic_cross_kernel(X_landmarks, X_landmarks, p, "D")

    additive_diagonal = (
        np.sum((Xtr_raw - 2.0 * p) ** 2, axis=1)
        / max(2.0 * np.sum(p * q), 1e-12)
    )

    rounded_genotypes = np.rint(Xtr_raw).clip(0, 2)
    dominance_codes = np.where(
        rounded_genotypes < 0.5,
        -2.0 * p**2,
        np.where(rounded_genotypes < 1.5, 2.0 * p * q, -2.0 * q**2),
    )
    dominance_diagonal = (
        np.sum(dominance_codes**2, axis=1)
        / max(np.sum((2.0 * p * q) ** 2), 1e-12)
    )

    additive_scale = max(float(additive_diagonal.mean()), 1e-12)
    dominance_scale = max(float(dominance_diagonal.mean()), 1e-12)
    epistatic_scale = max(float((additive_diagonal**2).mean()), 1e-12)

    train_cross_kernel = (
        A_train / additive_scale
        + D_train / dominance_scale
        + A_train**2 / epistatic_scale
    ) / 3.0
    test_cross_kernel = (
        A_test / additive_scale
        + D_test / dominance_scale
        + A_test**2 / epistatic_scale
    ) / 3.0
    landmark_kernel = (
        A_landmarks / additive_scale
        + D_landmarks / dominance_scale
        + A_landmarks**2 / epistatic_scale
    ) / 3.0

    transform = nystrom_transform(landmark_kernel)
    train_features = train_cross_kernel @ transform
    test_features = test_cross_kernel @ transform

    model = RidgeCV(
        alphas=np.logspace(-3, 3, 30),
        cv=min(3, n_folds),
        scoring="neg_root_mean_squared_error",
    ).fit(train_features, ytr)

    print(
        f"RKHS-Extended: alpha={model.alpha_:.6g}, "
        f"landmarks={len(landmarks)}"
    )
    return model.predict(test_features)

