def prepare_outer_cv_fold(train_idx, validation_idx):
    """
    Ajusta todo o pré-processamento exclusivamente no treino do fold.

    A padronização de Y usa média e desvio-padrão do treino do fold.
    Assim:
      viés padronizado = média(pred_std - real_std)
      variância padronizada = Var(real_std - pred_std)
    """
    X_train_df = X_CV_DF.iloc[train_idx].copy()
    X_validation_df = X_CV_DF.iloc[validation_idx].copy()

    y_train_original = Y_CV_ORIG[train_idx]
    y_validation_original = Y_CV_ORIG[validation_idx]

    fold_imputer = SimpleImputer(
        strategy="mean",
    )

    X_train_imputed = fold_imputer.fit_transform(
        X_train_df
    )

    X_validation_imputed = fold_imputer.transform(
        X_validation_df
    )

    if (
        not np.isfinite(X_train_imputed).all()
        or not np.isfinite(X_validation_imputed).all()
    ):
        raise ValueError(
            "Valores inválidos após a imputação dentro do fold."
        )

    allele_frequency = (
        X_train_imputed.mean(axis=0)
        / 2.0
    )

    fold_maf = np.minimum(
        allele_frequency,
        1.0 - allele_frequency,
    )

    fold_keep = (
        np.isfinite(fold_maf)
        & (fold_maf >= MAF_THRESHOLD)
        & (fold_maf <= 0.50)
    )

    if fold_keep.sum() == 0:
        raise ValueError(
            "Nenhum marcador permaneceu após o filtro de MAF no fold."
        )

    fold_marker_names = np.asarray(
        X_CV_DF.columns,
        dtype=str,
    )[fold_keep]

    X_train_raw_fold = X_train_imputed[
        :,
        fold_keep,
    ].astype(np.float64)

    X_validation_raw_fold = X_validation_imputed[
        :,
        fold_keep,
    ].astype(np.float64)

    fold_x_scaler = StandardScaler()

    X_train_scaled_fold = fold_x_scaler.fit_transform(
        X_train_raw_fold
    ).astype(np.float32)

    X_validation_scaled_fold = fold_x_scaler.transform(
        X_validation_raw_fold
    ).astype(np.float32)

    y_train_mean = float(
        np.mean(y_train_original)
    )

    y_train_scale = float(
        np.std(
            y_train_original,
            ddof=0,
        )
    )

    if (
        not np.isfinite(y_train_scale)
        or y_train_scale < 1e-12
    ):
        raise ValueError(
            "O desvio-padrão de Y no treino do fold é zero."
        )

    y_train_standardized = (
        (
            y_train_original
            - y_train_mean
        )
        / y_train_scale
    ).astype(np.float32)

    y_validation_standardized = (
        (
            y_validation_original
            - y_train_mean
        )
        / y_train_scale
    ).astype(np.float32)

    return {
        "train_idx": train_idx,
        "validation_idx": validation_idx,
        "X_train_raw": X_train_raw_fold,
        "X_validation_raw": X_validation_raw_fold,
        "X_train": X_train_scaled_fold,
        "X_validation": X_validation_scaled_fold,
        "X_train_3d": X_train_scaled_fold[
            ...,
            np.newaxis,
        ],
        "X_validation_3d": X_validation_scaled_fold[
            ...,
            np.newaxis,
        ],
        "y_train_original": y_train_original,
        "y_validation_original": y_validation_original,
        "y_train": y_train_standardized,
        "y_validation": y_validation_standardized,
        "y_mean": y_train_mean,
        "y_scale": y_train_scale,
        "marker_names": fold_marker_names,
    }


def activate_fold_context(fold_data):
    """
    Atualiza o contexto global usado pelas funções existentes dos modelos.

    O código dos modelos não é alterado; apenas os dados ativos passam a ser
    os dados de treino e validação do fold externo atual.
    """
    global Xtr_raw
    global Xte_raw
    global Xtr
    global Xte
    global Xtr3
    global Xte3
    global ytr
    global yte
    global n_markers
    global marker_names
    global n_folds
    global cv_splits
    global stacking_base_cache
    global stacking_meta_info
    global cv_records

    Xtr_raw = fold_data[
        "X_train_raw"
    ]

    Xte_raw = fold_data[
        "X_validation_raw"
    ]

    Xtr = fold_data[
        "X_train"
    ]

    Xte = fold_data[
        "X_validation"
    ]

    Xtr3 = fold_data[
        "X_train_3d"
    ]

    Xte3 = fold_data[
        "X_validation_3d"
    ]

    ytr = fold_data[
        "y_train"
    ]

    yte = fold_data[
        "y_validation"
    ]

    marker_names = fold_data[
        "marker_names"
    ]

    n_markers = Xtr.shape[1]

    n_folds = min(
        INNER_CV_FOLDS,
        len(ytr),
    )

    if n_folds < 2:
        raise ValueError(
            "Amostra insuficiente para a validação interna do modelo."
        )

    cv_splits = list(
        KFold(
            n_splits=n_folds,
            shuffle=True,
            random_state=SEED + CURRENT_OUTER_FOLD,
        ).split(Xtr)
    )

    stacking_base_cache.clear()
    stacking_meta_info.clear()
    cv_records.clear()


def calculate_standardized_fold_metrics(
    y_true_standardized,
    y_pred_standardized,
):
    """
    Calcula todas as métricas no fold de validação.

    Viés, RMSE, MAE, variância e desvio residual estão expressos em
    unidades de desvio-padrão do Y de treino daquele fold.
    """
    y_true_standardized = np.asarray(
        y_true_standardized,
        dtype=float,
    ).ravel()

    y_pred_standardized = np.asarray(
        y_pred_standardized,
        dtype=float,
    ).ravel()

    if (
        len(y_true_standardized)
        != len(y_pred_standardized)
    ):
        raise ValueError(
            "Y real e Y predito possuem tamanhos diferentes."
        )

    if (
        not np.isfinite(y_true_standardized).all()
        or not np.isfinite(y_pred_standardized).all()
    ):
        raise ValueError(
            "Há valores não finitos nas métricas do fold."
        )

    standardized_residuals = (
        y_true_standardized
        - y_pred_standardized
    )

    return {
        "Acurácia preditiva CV (Pearson)": (
            predictive_pearson(
                y_true_standardized,
                y_pred_standardized,
            )
        ),
        "R² CV": float(
            r2_score(
                y_true_standardized,
                y_pred_standardized,
            )
        ),
        "SRMSE CV padronizado": float(
            np.sqrt(
                mean_squared_error(
                    y_true_standardized,
                    y_pred_standardized,
                )
            )
        ),
        "MAE CV padronizado": float(
            mean_absolute_error(
                y_true_standardized,
                y_pred_standardized,
            )
        ),
        "Viés CV padronizado": float(
            np.mean(
                y_pred_standardized
                - y_true_standardized
            )
        ),
        "Inclinação de calibração CV (b)": (
            calibration_slope(
                y_true_standardized,
                y_pred_standardized,
            )
        ),
        "Variância residual CV padronizada": float(
            np.var(
                standardized_residuals,
                ddof=1,
            )
        ),
        "Desvio residual CV padronizado": float(
            np.std(
                standardized_residuals,
                ddof=1,
            )
        ),
        "Hit Rate CV": hit_rate(
            y_true_standardized,
            y_pred_standardized,
        ),
        "NDCG CV": ndcg_score_rank(
            y_true_standardized,
            y_pred_standardized,
        ),
    }


def fit_predict_current_fold(model_name):
    """
    Ajusta um modelo no treino do fold e prediz somente a validação do fold.

    Nenhuma métrica é calculada sobre X_val/Y_val_gv.
    """
    if model_name == "TabPFN-3":
        return fit_tabpfn3()

    if model_name == "CatBoost":
        model = catboost_model()
        model.fit(
            Xtr,
            ytr,
        )
        prediction = model.predict(
            Xte
        )
        del model
        gc.collect()
        return prediction

    if model_name == "AttentionNet":
        return fit_neural_network(
            "AttentionNet",
            build_attention_net,
            Xtr,
            ytr,
            Xte,
        )

    if model_name == "Bayesian Ridge":
        model = BayesianRidge()
        model.fit(
            Xtr,
            ytr,
        )
        prediction = model.predict(
            Xte
        )
        del model
        gc.collect()
        return prediction

    if model_name == "CNN":
        return fit_neural_network(
            "CNN",
            build_cnn,
            Xtr3,
            ytr,
            Xte3,
        )

    if model_name == "DNN":
        return fit_neural_network(
            "DNN",
            build_dnn,
            Xtr,
            ytr,
            Xte,
        )

    if model_name == "LGBM+NN":
        return fit_lgbm_plus_nn()

    if model_name == "RKHS-Extended":
        return fit_rkhs_extended()

    if model_name == "RKHS":
        return fit_rkhs_rbf()

    if model_name == "Stacking":
        return fit_stacking()

    raise ValueError(
        f"Modelo ativo não reconhecido: {model_name}"
    )


